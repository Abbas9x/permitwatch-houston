// Checklist for finding missing plant locations by hand. Lists every plant in
// data/concrete-plants.json without coordinates, with TCEQ's Central Registry
// location description and map links, and writes data/missing-locations.md.
// Found locations go in scraper/manual-locations.json.
//
// Usage: npm run lookups  (run npm run scrape first)

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as cheerio from "cheerio";
import { parseSearchResults } from "./existing.js";
import { RAW_DIR, cachedPostForm } from "./http.js";
import { OUTPUT_PATH as PLANTS_PATH } from "./scrape.js";
import type { PlantsFile } from "./types.js";

const OUTPUT_PATH = fileURLToPath(new URL("../../data/missing-locations.md", import.meta.url));
const REGISTRY_URL = "https://www15.tceq.texas.gov/crpub/index.cfm";
const REGISTRY_SEARCH_URL = `${REGISTRY_URL}?fuseaction=regent.newSearch`;

interface RegistryEntry {
  streetAddress: string | null;
  physicalLocation: string | null;
  nearZip: string | null;
}

/** The location fields of a Central Registry regulated entity page. */
async function lookUpRegistry(rn: string): Promise<RegistryEntry> {
  const form = new URLSearchParams({ re_ref_num_txt: rn, "_fuseaction=regent.validateRE": "Search" });
  const html = await cachedPostForm(REGISTRY_URL, form, REGISTRY_SEARCH_URL, join(RAW_DIR, "registry", `${rn}.html`));
  const text = cheerio.load(html.toString("utf8")).text().replace(/\s+/g, " ");
  const field = (label: string, next: string) =>
    text.match(new RegExp(`${label}:\\s*(.*?)\\s*${next}:`))?.[1]?.trim() || null;
  const street = field("Street Address", "County");
  const location = text.match(/Physical Location:\s*(.*?)\s*Affiliated Customers/)?.[1]?.trim();
  return {
    streetAddress: street && !/^No street address/i.test(street) ? street : null,
    physicalLocation: location && !/^No physical location/i.test(location) ? location : null,
    nearZip: field("Near ZIP Code", "Physical Location"),
  };
}

const mapsLink = (q: string) => `https://www.google.com/maps/search/${encodeURIComponent(q)}`;
const osmLink = (q: string) => `https://www.openstreetmap.org/search?query=${encodeURIComponent(q)}`;

async function main() {
  const plants = (JSON.parse(await readFile(PLANTS_PATH, "utf8")) as PlantsFile).plants.filter((p) => p.lat === null);
  const projects = parseSearchResults(await readFile(join(RAW_DIR, "existing", "nsr-harris-cbp.html"), "utf8"));
  const rnByPermit = new Map(projects.map((p) => [p.permitNumber, p.regulatedEntity]));

  const lines = [
    "# Plants missing a map location",
    "",
    `${plants.length} plants in \`data/concrete-plants.json\` have no coordinates. For each one, find the plant on a satellite map (look for cement silos, aggregate piles and mixer trucks), then add it to \`scraper/manual-locations.json\` under its permit number:`,
    "",
    "```json",
    '"130567": { "lat": 29.0, "lng": -95.0, "note": "Coordinates entered by hand from a satellite map lookup of <what you searched>." }',
    "```",
    "",
    "Then run `npm run scrape`, `npm run demo` and `npm run validate` in `scraper/`. Generated by `npm run lookups`.",
    "",
  ];

  for (const [i, p] of plants.entries()) {
    const rn = p.permitNumber ? rnByPermit.get(p.permitNumber) : undefined;
    const registry = rn ? await lookUpRegistry(rn) : null;
    const query = `${p.address}, ${p.city ?? ""}, TX`;
    lines.push(
      `## ${i + 1}. Permit ${p.permitNumber}: ${p.operator ?? p.name}`,
      "",
      `- [ ] Found`,
      `- Permit search address: ${p.address}, ${p.city}`,
      ...(registry?.streetAddress ? [`- Central Registry street address: ${registry.streetAddress}`] : []),
      ...(registry?.physicalLocation ? [`- Central Registry location: ${registry.physicalLocation}`] : []),
      ...(registry?.nearZip ? [`- Near ZIP: ${registry.nearZip}`] : []),
      `- Why it's missing: ${p.notes ?? "unknown"}`,
      `- Maps: [Google Maps](${mapsLink(query)}) · [OpenStreetMap](${osmLink(query)})${rn ? ` · [TCEQ record](${REGISTRY_SEARCH_URL}) (${rn})` : ""}`,
      "",
    );
    console.log(`${i + 1}/${plants.length} ${p.permitNumber} ${registry?.physicalLocation ?? "-"}`);
  }

  await writeFile(OUTPUT_PATH, lines.join("\n"), "utf8");
  console.log(`Wrote ${OUTPUT_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
